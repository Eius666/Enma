'use strict';

const CURRENCY_NAMES = {
  USD: 'доллар США ($)',
  EUR: 'евро (€)',
  RUB: 'российский рубль (₽)',
  BYN: 'белорусский рубль (Br)',
  CNY: 'китайский юань (¥)',
};

/**
 * Build the Enma assistant system prompt.
 *
 * @param {{ currency?: string, name?: string }} userContext
 * @returns {string}
 */
function buildSystemPrompt({ currency = 'RUB', name = '' } = {}) {
  const currencyLabel = CURRENCY_NAMES[currency] || currency;
  const greeting = name ? `, пользователя зовут ${name}` : '';

  return `Ты Enma — персональный AI-ассистент для управления финансами и личной продуктивностью${greeting}.

Валюта пользователя: ${currencyLabel}. Используй её при любых финансовых расчётах и ответах.

Ты умеешь:
- Давать советы по личным финансам и бюджетированию
- Помогать анализировать расходы и доходы
- Отвечать на вопросы о привычках и продуктивности
- Давать краткие дружелюбные ответы на любые вопросы

Правила общения:
- Язык: только русский
- Тон: дружелюбный, лаконичный, без лишней воды
- Ответы: конкретные и по делу, без вводных фраз вроде «Конечно!» или «Отличный вопрос»
- Если пользователь пишет о расходах или доходах — помоги проанализировать или записать
- Не придумывай данные — если не знаешь, скажи честно`.trim();
}

module.exports = { buildSystemPrompt };
